"""Generate Databricks artifacts from the parsed PowerCenter model."""
from __future__ import annotations

from pathlib import Path

from infa2dbx.expr import translate_expression
from infa2dbx.parser import Mapping, Repository, Transform, topo_order

LINEAR = {"Source Qualifier", "Lookup Procedure", "Expression", "Filter", "Aggregator",
          "Sequence Generator", "Update Strategy", "Sorter", "Rank", "Joiner", "SQL"}


def _source_of(t: Transform, repo: Repository) -> str:
    sql = t.attrs.get("Sql Query", "")
    for ds in repo.datasets:
        if ds.kind == "SOURCE" and ds.name in sql.upper():
            return ds.name
    return t.name.replace("SQ_", "")


def _lookup_of(t: Transform) -> str:
    return t.attrs.get("Lookup table name", t.name.replace("LKP_", ""))


def _join_key(t: Transform) -> str:
    cond = t.attrs.get("Lookup condition", "")
    if "=" in cond:
        return cond.split("=")[0].split(".")[-1].strip()
    return "ID"


def is_linear(mapping: Mapping) -> bool:
    return all(t.type in LINEAR for t in mapping.transforms)


def _transform_lines(t: Transform, repo: Repository, var: str = "df") -> list[str]:
    """Emit code for one transformation operating on DataFrame `var`."""
    typ = t.type
    if typ == "Source Qualifier":
        src = _source_of(t, repo)
        return [f'{var} = spark.read.parquet(f"{{bridge}}/{src.lower()}")']
    if typ == "Lookup Procedure":
        tbl = _lookup_of(t).lower()
        key = _join_key(t)
        return [f'_lk = spark.read.parquet(f"{{bridge}}/{tbl}")',
                f'{var} = {var}.join(_lk, on="{key}", how="left")']
    if typ == "Joiner":
        cond = t.attrs.get("Join Condition", "")
        jtype = t.attrs.get("Join Type", "Normal Join")
        how = {"Normal Join": "inner", "Master Outer": "left", "Detail Outer": "right",
               "Full Outer": "full"}.get(jtype, "inner")
        key = cond.split("=")[0].split(".")[-1].strip() if "=" in cond else "ID"
        return [f'{var} = {var}.join(_other, on="{key}", how="{how}")  # {cond}']
    if typ == "Expression":
        out = []
        for f in t.fields:
            if f.expression:
                out.append(f'{var} = {var}.withColumn("{f.name}", {translate_expression(f.expression)})')
        return out or [f"# {t.name}: no expressions"]
    if typ == "Filter":
        cond = t.attrs.get("Filter Condition", "1=1")
        return [f'{var} = {var}.filter({translate_expression(cond)})']
    if typ == "Aggregator":
        gb = [f.name for f in t.fields if f.porttype.upper() == "GROUP BY"]
        aggs = [f for f in t.fields if f.porttype.upper() == "OUTPUT" and f.expression]
        agg_expr = ", ".join(f"{translate_expression(f.expression)}.alias('{f.name}')" for f in aggs)
        return [f'{var} = {var}.groupBy({", ".join(repr(c) for c in gb)}).agg({agg_expr})']
    if typ == "Sequence Generator":
        key = t.fields[0].name if t.fields else "SEQ_KEY"
        return [f'{var} = {var}.withColumn("{key}", F.monotonically_increasing_id() + 1)']
    if typ == "Sorter":
        keys = t.attrs.get("Sort Key", "").replace(",", " ")
        cols = [c for c in keys.split() if c.upper() not in ("ASC", "DESC")]
        return [f'{var} = {var}.orderBy({", ".join(repr(c) for c in cols)})  # {keys}']
    if typ == "Rank":
        top = t.attrs.get("Number of Ranks", "10")
        by = t.attrs.get("Rank Port", "AMOUNT_BASE")
        return ["from pyspark.sql import Window",
                f'{var} = {var}.withColumn("_rank", F.rank().over(Window.orderBy(F.desc("{by}"))))',
                f'{var} = {var}.filter(F.col("_rank") <= {top}).drop("_rank")']
    if typ == "Union":
        return ["# Union -> unionByName of the input branches (adjust view names)",
                f'{var} = spark.table("branch_a").unionByName(spark.table("branch_b"), allowMissingColumns=True)']
    if typ == "Normalizer":
        cols = [f.name for f in t.fields if f.porttype.upper().startswith("OUTPUT")][:1] or ["VALUE"]
        return [f"# Normalizer -> explode rows",
                f'{var} = {var}.select("*", F.explode(F.array({", ".join(repr(c) for c in cols)})).alias("NORM_VALUE"))']
    if typ == "SQL":
        q = t.attrs.get("Sql Query", "SELECT * FROM in_view")
        return [f'{var}.createOrReplaceTempView("in_view")', f'{var} = spark.sql("""{q}""")']
    if typ == "Update Strategy":
        strat = t.attrs.get("Update Strategy Expression", "DD_UPDATE")
        return [f"# Update Strategy {strat} -> Delta MERGE into the target"]
    return [f"# TODO: {typ} not auto-translated"]


def build_notebook(mapping: Mapping, repo: Repository) -> tuple[str, list]:
    lines = ["# Databricks notebook source", "# MAGIC %md",
             f"# {mapping.name} (migrated from Informatica PowerCenter)",
             "# MAGIC Generated by infa2dbx. Review before production.", "",
             "# COMMAND ----------", "from pyspark.sql import functions as F", ""]
    rows = []
    for t in topo_order(mapping):
        lines += ["# COMMAND ----------", f"# MAGIC %md ## {t.name}  ({t.type})", ""]
        if t.type == "Router":
            parts = [(name, translate_expression(cond)) for name, cond in t.groups if cond]
            if parts:
                expr = f'F.when({parts[0][1]}, "{parts[0][0]}")'
                for name, cond in parts[1:]:
                    expr += f'.when({cond}, "{name}")'
                expr += '.otherwise("DEFAULT")'
            else:
                expr = 'F.lit("DEFAULT")'
            lines += [f'df = df.withColumn("ROUTE", {expr})']
            for name, _ in t.groups:
                lines.append(f'df.filter(F.col("ROUTE") == "{name}").createOrReplaceTempView("{name.lower()}")')
            rows.append((t.name, t.type, f'route by {[g[0] for g in t.groups]}'))
            continue
        code = _transform_lines(t, repo)
        lines += code
        rows.append((t.name, t.type, "; ".join(c.strip() for c in code)[:80]))
    return "\n".join(lines) + "\n", rows


def build_module(mapping: Mapping, repo: Repository) -> str:
    """A runnable module with run(spark, bridge) for linear mappings (verify)."""
    lines = [
        f'"""Runnable transform generated by infa2dbx from mapping {mapping.name}."""',
        "from pyspark.sql import functions as F",
        "",
        "",
        "def run(spark, bridge):",
        "    df = None",
    ]
    for t in topo_order(mapping):
        code = _transform_lines(t, repo, var="df")
        lines += ["    " + c for c in code]
    lines += ["    return df", ""]
    return "\n".join(lines)


def build_workflow(wf) -> dict:
    TASK_KIND = {"Session": "notebook", "Worklet": "sub-workflow", "Decision": "conditional",
                 "Command": "python_task", "Email": "notification", "Start": "start",
                 "Timer": "schedule"}
    deps = {}
    for f, t in wf.links:
        deps.setdefault(t, []).append(f)
    tasks = []
    for t in wf.tasks:
        if t.type == "Start":
            continue
        tasks.append({"task_key": t.name, "kind": TASK_KIND.get(t.type, "notebook"),
                      "depends_on": [{"task_key": d} for d in deps.get(t.name, []) if d != "start"]})
    return {"name": wf.name, "schedule": wf.schedule,
            "parameters": [{"name": n, "default": v} for n, v, _ in wf.variables],
            "tasks": tasks}


_TYPE_SPARK = {"string": "StringType()", "integer": "LongType()", "decimal": None, "date/time": "DateType()"}


def build_schema(repo: Repository) -> str:
    lines = ['"""StructTypes derived from PowerCenter sources/targets."""',
             "from pyspark.sql.types import (StructType, StructField, StringType,",
             "                               LongType, DecimalType, DateType)", ""]
    for ds in repo.datasets:
        lines.append(f"# {ds.kind} {ds.name} ({ds.dbtype})")
        lines.append(f"{ds.name}_SCHEMA = StructType([")
        for f in ds.fields:
            st = (f"DecimalType({f.precision}, {f.scale})" if f.datatype == "decimal"
                  else _TYPE_SPARK.get(f.datatype, "StringType()"))
            lines.append(f'    StructField("{f.name}", {st}, True),')
        lines.append("])")
        lines.append("")
    return "\n".join(lines)
